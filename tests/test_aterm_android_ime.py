"""The generated MainActivity is replaced so the keyboard clears the message box (COI-3575)."""

from __future__ import annotations

from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "aterm-android/src-tauri/gen/android/app/src/main"


def _tree(tmp_path: Path, generated: list[str]) -> Path:
    script = tmp_path / "scripts" / "ci" / "aterm-android.sh"
    script.parent.mkdir(parents=True)
    shutil.copy(ROOT / "scripts" / "ci" / "aterm-android.sh", script)
    ours = tmp_path / "aterm-android" / "android" / "MainActivity.kt"
    ours.parent.mkdir(parents=True)
    shutil.copy(ROOT / "aterm-android" / "android" / "MainActivity.kt", ours)
    for rel in generated:
        target = tmp_path / GENERATED / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("// generated by tauri\n")
    return tmp_path


def _patch(tree: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["bash", str(tree / "scripts" / "ci" / "aterm-android.sh"), "ime-patch"],
        capture_output=True,
        text=True,
        check=False,
    )


def test_the_generated_activity_is_replaced_by_ours(tmp_path: Path) -> None:
    tree = _tree(tmp_path, ["java/dev/coilyco/treehouse/MainActivity.kt"])
    done = _patch(tree)
    assert done.returncode == 0, done.stderr
    generated = tree / GENERATED / "java/dev/coilyco/treehouse/MainActivity.kt"
    assert generated.read_text() == (ROOT / "aterm-android/android/MainActivity.kt").read_text()


def test_a_project_with_no_activity_is_refused(tmp_path: Path) -> None:
    tree = _tree(tmp_path, [])
    (tree / GENERATED).mkdir(parents=True)
    done = _patch(tree)
    assert done.returncode != 0
    assert "expected one generated MainActivity.kt" in done.stderr


def test_a_project_with_two_activities_is_refused_and_left_alone(tmp_path: Path) -> None:
    tree = _tree(tmp_path, ["java/a/MainActivity.kt", "java/b/MainActivity.kt"])
    done = _patch(tree)
    assert done.returncode != 0
    assert (tree / GENERATED / "java/a/MainActivity.kt").read_text() == "// generated by tauri\n"
