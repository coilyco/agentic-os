#!/usr/bin/env python3
"""Generate the seat variant of the guarded `gh` guardfile from the container one.

Both guardfiles carry one policy. They differ in what the replacement execs: a
container runs no aterm daemon, so it execs `gh` itself, and a native seat execs
`aterm gh-exec`, which mints a per-repo App token (COI-2933). Deriving the seat
file from the container one is what keeps the policy from drifting, and `--check`
fails when the committed copy is anything but that derivation.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".umbra" / "shims" / "gh" / "gh.kdl"
TARGET = ROOT / ".umbra" / "shims-seat" / "gh" / "gh.kdl"

# The source's own two-line header is replaced, so the cap on a file's leading
# comment holds here too.
HEADER = (
    "// GENERATED by generate_gh_seat_guardfile.py from ../../shims/gh/gh.kdl, which\n"
    "// is the file to edit. Only the exec lines differ.\n"
)

EXEC_LINES = ("    exec gh\n", "    replace\n")
SEAT_EXEC_LINES = ('    exec aterm {\n        argv-prefix "gh-exec"\n    }\n', '    replace "gh"\n')


def render(source: str) -> str:
    """The seat guardfile for a container guardfile's text."""
    lines = source.splitlines(keepends=True)
    while lines and lines[0].startswith("//"):
        lines.pop(0)
    out = "".join(lines)
    for container, seat in zip(EXEC_LINES, SEAT_EXEC_LINES):
        if out.count(container) != 1:
            raise ValueError(f"expected exactly one {container.strip()!r} line in the source")
        out = out.replace(container, seat)
    return HEADER + out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args(argv)
    wanted = render(SOURCE.read_text(encoding="utf-8"))
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != wanted:
            print(f"{TARGET.relative_to(ROOT)} is not the derivation of {SOURCE.relative_to(ROOT)}. Run: just gh-seat-guardfile", file=sys.stderr)
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(wanted, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
