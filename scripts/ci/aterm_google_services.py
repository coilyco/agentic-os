"""Turn a deployment's google-services.json into the string resources Firebase reads.

The Treehouse build does what the google-services Gradle plugin would, so the JSON stays
in deployment config. Reads the JSON on stdin and the application id as the argument,
writes the resource XML on stdout. Errors name the field and never a value.
Contract: tooling-aterm-client references/android-push.md.
"""

from __future__ import annotations

import json
import sys
from xml.sax.saxutils import escape


class ConfigError(ValueError):
    """The JSON is not a google-services.json with a client for this application."""


def _field(source: dict, *path: str) -> str:
    value: object = source
    for key in path:
        if not isinstance(value, dict) or key not in value:
            raise ConfigError(f"google-services.json has no {'.'.join(path)}")
        value = value[key]
    if not isinstance(value, str) or not value:
        raise ConfigError(f"google-services.json has an empty {'.'.join(path)}")
    return value


def resources(config: dict, app_id: str) -> dict[str, str]:
    """The values FirebaseOptions.fromResource reads, for the client registered as app_id."""
    clients = config.get("client")
    if not isinstance(clients, list):
        raise ConfigError("google-services.json has no client list")
    for client in clients:
        info = client.get("client_info", {}) if isinstance(client, dict) else {}
        if info.get("android_client_info", {}).get("package_name") != app_id:
            continue
        keys = client.get("api_key")
        if not isinstance(keys, list) or not keys or not isinstance(keys[0], dict):
            raise ConfigError("google-services.json has no api_key for this client")
        values = {
            "google_app_id": _field(info, "mobilesdk_app_id"),
            "google_api_key": _field(keys[0], "current_key"),
            "gcm_defaultSenderId": _field(config, "project_info", "project_number"),
            "project_id": _field(config, "project_info", "project_id"),
        }
        bucket = config.get("project_info", {}).get("storage_bucket")
        if isinstance(bucket, str) and bucket:
            values["google_storage_bucket"] = bucket
        return values
    raise ConfigError(f"google-services.json has no Android client for {app_id}")


def render(values: dict[str, str]) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by scripts/ci/aterm_google_services.py. -->", "<resources>"]
    for name, value in values.items():
        lines.append(f'    <string name="{name}" translatable="false">{escape(value)}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: aterm_google_services.py APP_ID < google-services.json", file=sys.stderr)
        return 2
    try:
        config = json.loads(sys.stdin.read())
        if not isinstance(config, dict):
            raise ConfigError("google-services.json is not a JSON object")
        sys.stdout.write(render(resources(config, argv[1])))
    except json.JSONDecodeError:
        print("google-services.json is not valid JSON", file=sys.stderr)
        return 1
    except ConfigError as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
